-- 3. Habilita acesso de leitura público para qualquer visitante do site
ALTER TABLE public.aparencia ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Acesso de leitura publico para aparencia" 
ON public.aparencia FOR SELECT 
USING (true);

-- 4. Habilita acesso de modificação para usuários autenticados (Admin)
CREATE POLICY "Permitir update para usuarios autenticados" 
ON public.aparencia FOR UPDATE 
TO authenticated 
USING (true)
WITH CHECK (true);

CREATE POLICY "Permitir insert para usuarios autenticados" 
ON public.aparencia FOR INSERT 
TO authenticated 
WITH CHECK (true);
