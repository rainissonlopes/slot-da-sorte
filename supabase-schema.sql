-- Script SQL para Criar a Tabela de Aparência (White-Label)

-- 1. Cria a tabela aparencia
CREATE TABLE IF NOT EXISTS public.aparencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    domain TEXT NOT NULL DEFAULT 'default' UNIQUE,
    nome_site TEXT NOT NULL DEFAULT 'Slot da Sorte',
    logo_url TEXT,
    favicon_url TEXT,
    cor_primaria TEXT NOT NULL DEFAULT '#00ff66',
    cor_secundaria TEXT NOT NULL DEFAULT '#FFC801',
    titulo_home TEXT NOT NULL DEFAULT 'SINAIS DE SLOT EM TEMPO REAL',
    subtitulo_home TEXT NOT NULL DEFAULT 'A plataforma de sinais mais assertiva do mercado.',
    texto_cta TEXT NOT NULL DEFAULT 'Acessar Plataforma',
    banner_principal_url TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

